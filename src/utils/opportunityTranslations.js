export function translateOpportunity(opp, lang) {
  if (!opp) return opp;
  if (lang === 'es' || !lang) return opp;

  const clone = { ...opp };
  const translations = OPPORTUNITY_TRANSLATIONS[lang];

  // 1. Direct ID match from comprehensive dictionary
  if (translations && translations[clone.id]) {
    const t = translations[clone.id];
    if (t.title) clone.title = t.title;
    if (t.organization) clone.organization = t.organization;
    if (t.type) clone.type = t.type;
    if (t.description) clone.description = t.description;
    if (t.coverageLabel) clone.coverageLabel = t.coverageLabel;
    if (t.location) clone.location = t.location;
    if (t.ageRangeLabel) clone.ageRangeLabel = t.ageRangeLabel;
    if (t.requirements && t.requirements.length) clone.requirements = t.requirements;
    if (t.benefits && t.benefits.length) clone.benefits = t.benefits;
    if (t.steps && t.steps.length) clone.steps = t.steps;
    return clone;
  }

  // 2. Organization mapping
  if (clone.organization) {
    const orgMap = lang === 'en' ? ORG_MAP_EN : ORG_MAP_QU;
    const cleanOrg = clone.organization.trim();
    if (orgMap[cleanOrg]) {
      clone.organization = orgMap[cleanOrg];
    } else {
      for (const [k, v] of Object.entries(orgMap)) {
        if (cleanOrg.toLowerCase().includes(k.toLowerCase())) {
          clone.organization = v;
          break;
        }
      }
    }
  }

  // 3. NLP Sentence and Regex Glossary Translation
  const rules = lang === 'en' ? NLP_RULES_EN : NLP_RULES_QU;
  
  if (clone.title) {
    for (const [regex, replacement] of rules) {
      if (regex.test(clone.title)) {
        clone.title = clone.title.replace(regex, replacement);
      }
    }
  }

  if (clone.description) {
    for (const [regex, replacement] of rules) {
      if (regex.test(clone.description)) {
        clone.description = clone.description.replace(regex, replacement);
      }
    }
  }

  // 4. Modality, Coverage and Location Fallbacks
  if (lang === 'en') {
    if (clone.coverage === 'full' || clone.coverageLabel?.includes('100%')) clone.coverageLabel = '100% Full Coverage';
    else if (clone.coverage === 'partial') clone.coverageLabel = 'Partial Coverage';

    if (clone.modality === 'remote') clone.location = '100% Online / Remote';
    else if (clone.modality === 'hybrid') clone.location = 'Hybrid (Online & Onsite)';
    else if (clone.modality === 'onsite' && (!clone.location || clone.location.includes('Nacional'))) clone.location = 'Nationwide (All Peru)';

    if (clone.ageRange === 'under18') clone.ageRangeLabel = '15 to 18 years old';
    else if (clone.ageRange === '18to25') clone.ageRangeLabel = '18 to 25 years old';
    else if (clone.ageRange === 'over25') clone.ageRangeLabel = '25+ years old';
  } else if (lang === 'qu') {
    if (clone.coverage === 'full' || clone.coverageLabel?.includes('100%')) clone.coverageLabel = '100% Tukuy Yanapasqa';
    else if (clone.coverage === 'partial') clone.coverageLabel = 'Chawpi Yanapasqa';

    if (clone.modality === 'remote') clone.location = 'Internetpi / Karumanta';
    else if (clone.modality === 'hybrid') clone.location = 'Chaqrusqa (Internetwan Chaypipas)';
    else if (clone.modality === 'onsite' && (!clone.location || clone.location.includes('Nacional'))) clone.location = 'Suyuntin (Tukuy Perú)';

    if (clone.ageRange === 'under18') clone.ageRangeLabel = '15 watamanta 18 watakama';
    else if (clone.ageRange === '18to25') clone.ageRangeLabel = '18 watamanta 25 watakama';
    else if (clone.ageRange === 'over25') clone.ageRangeLabel = '25 wata aswan';
  }

  return clone;
}
