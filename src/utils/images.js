// Global tracker to ensure absolute ZERO repetition
const usedImagesSet = new Set();

export function getUniqueImage(opp) {
  if (!opp) return 'https://images.unsplash.com/photo-1523240795612-9a054b0db644?w=500&h=350&fit=crop';
  
  const title = (opp.title || '').toLowerCase();
  const org = (opp.organization || '').toLowerCase();
  const desc = (opp.description || '').toLowerCase();
  const category = opp.category || 'scholarship';

  const fullText = `${title} ${org} ${desc}`;
  
  let targetKey = '';

  if (category === 'scholarship') {
    if (fullText.includes('ingeniería') || fullText.includes('sistemas') || fullText.includes('tech') || fullText.includes('software')) targetKey = 'engineering';
    else if (fullText.includes('medicina') || fullText.includes('salud') || fullText.includes('médico') || fullText.includes('psicología')) targetKey = 'medicine';
    else if (fullText.includes('internacional') || fullText.includes('extranjero') || fullText.includes('intercambio') || fullText.includes('exterior')) targetKey = 'international_scholarship';
    else if (fullText.includes('investigación') || fullText.includes('ciencia') || fullText.includes('científico')) targetKey = 'research';
    else if (fullText.includes('negocio') || fullText.includes('administración') || fullText.includes('banco') || fullText.includes('bcp') || fullText.includes('finanzas')) targetKey = 'finance';
    else targetKey = 'scholarship_default';
  } 
  else if (category === 'course') {
    if (fullText.includes('inteligencia artificial') || fullText.includes('ia') || fullText.includes('machine learning')) targetKey = 'ai';
    else if (fullText.includes('programación') || fullText.includes('react') || fullText.includes('software') || fullText.includes('frontend') || fullText.includes('backend') || fullText.includes('código')) targetKey = 'programming';
    else if (fullText.includes('ciberseguridad') || fullText.includes('seguridad') || fullText.includes('hacker')) targetKey = 'cybersecurity';
    else if (fullText.includes('inglés') || fullText.includes('idioma') || fullText.includes('english')) targetKey = 'english';
    else if (fullText.includes('datos') || fullText.includes('data') || fullText.includes('python') || fullText.includes('analytics')) targetKey = 'data_analysis';
    else targetKey = 'course_default';
  }
  else if (category === 'job') {
    if (fullText.includes('ingeniero') || fullText.includes('desarrollador') || fullText.includes('programador') || fullText.includes('software')) targetKey = 'programming';
    else if (fullText.includes('marketing') || fullText.includes('ventas') || fullText.includes('comercial')) targetKey = 'marketing';
    else if (fullText.includes('finanzas') || fullText.includes('banco') || fullText.includes('contable')) targetKey = 'finance';
    else if (fullText.includes('remoto') || fullText.includes('home office')) targetKey = 'remote';
    else if (fullText.includes('atención') || fullText.includes('cliente') || fullText.includes('soporte')) targetKey = 'customer_service';
    else targetKey = 'job_default';
  }
  else if (category === 'volunteer') {
    if (fullText.includes('ambiental') || fullText.includes('reforestación') || fullText.includes('naturaleza') || fullText.includes('árboles')) targetKey = 'environmental';
    else if (fullText.includes('educación') || fullText.includes('enseñanza') || fullText.includes('tutoría') || fullText.includes('colegio')) targetKey = 'education_volunteer';
    else if (fullText.includes('comunidad') || fullText.includes('social') || fullText.includes('apoyo')) targetKey = 'community';
    else if (fullText.includes('salud') || fullText.includes('psicológico')) targetKey = 'medicine'; 
    else if (fullText.includes('humanitario') || fullText.includes('rescate') || fullText.includes('emergencia')) targetKey = 'humanitarian';
    else targetKey = 'volunteer_default';
  }

  // Handle cross-category fallbacks if targetKey isn't strictly defined but finance is needed
  if (targetKey === 'finance' && !unsplashCatalogs[targetKey]) targetKey = 'scholarship_default';

  let catalog = unsplashCatalogs[targetKey] || unsplashCatalogs[`${category}_default`] || unsplashCatalogs['scholarship_default'];
  
  let selectedImage = null;
  
  // Try to find a completely unused image in the most relevant catalog
  for (const img of catalog) {
    if (!usedImagesSet.has(img)) {
      selectedImage = img;
      break;
    }
  }

  // If all specific images are used, fallback to ANY unused image in the entire database
  if (!selectedImage) {
    for (const key in unsplashCatalogs) {
      for (const img of unsplashCatalogs[key]) {
        if (!usedImagesSet.has(img)) {
          selectedImage = img;
          break;
        }
      }
      if (selectedImage) break;
    }
  }

  // If absolutely every single image in the system has been used, clear the tracker and start over (mathematically almost impossible for standard views)
  if (!selectedImage) {
    usedImagesSet.clear();
    selectedImage = catalog[0]; 
  }

  // Mark as used
  usedImagesSet.add(selectedImage);

  return selectedImage;
}
