export function enrichOpportunity(opp) {
  if (!opp) return opp;
  const clone = { ...opp };

  // 1. Check direct UUID metadata
  if (UUID_METADATA[clone.id]) {
    const meta = UUID_METADATA[clone.id];
    Object.assign(clone, meta);
    return clone;
  }

  // 2. Intelligent inference based on category and title keywords
  const title = (clone.title || '').toLowerCase();
  const desc = (clone.description || '').toLowerCase();
  const org = (clone.organization || '').toLowerCase();
  const cat = clone.category || '';

  // MODALITY
  if (!clone.modality) {
    if (title.includes('remoto') || desc.includes('remoto') || title.includes('virtual') || desc.includes('online')) {
      clone.modality = 'remote';
    } else if (title.includes('híbrido') || desc.includes('híbrido') || title.includes('hibrido')) {
      clone.modality = 'hybrid';
    } else {
      clone.modality = 'onsite';
    }
  }

  // COVERAGE
  if (!clone.coverage) {
    if (title.includes('100%') || desc.includes('integral') || desc.includes('completa') || cat === 'scholarship' || cat === 'course') {
      clone.coverage = 'full';
    } else {
      clone.coverage = 'partial';
    }
  }

  // CATEGORY-SPECIFIC INFERENCE
  if (cat === 'course') {
    if (!clone.typeCategory) {
      if (title.includes('react') || title.includes('python') || title.includes('frontend') || title.includes('datos') || title.includes('ux') || title.includes('inteligencia') || title.includes('software') || title.includes('código') || title.includes('programación') || org.includes('laboratoria') || org.includes('platzi')) {
        clone.typeCategory = 'tecnologia';
      } else if (title.includes('marketing') || title.includes('proyectos') || title.includes('ágiles') || title.includes('finanzas') || title.includes('negocios') || title.includes('emprendimiento') || org.includes('crehana') || org.includes('asbanc')) {
        clone.typeCategory = 'negocios';
      } else if (title.includes('inglés') || title.includes('ingles') || title.includes('quechua') || title.includes('idioma') || org.includes('british')) {
        clone.typeCategory = 'idiomas';
      } else {
        clone.typeCategory = 'habilidades';
      }
    }
    if (!clone.ageRange) clone.ageRange = 'all';
  } else if (cat === 'scholarship') {
    if (!clone.typeCategory) {
      if (title.includes('beca 18') || org.includes('pronabec') || title.includes('continuidad') || title.includes('presidente')) {
        clone.typeCategory = 'beca18';
        clone.ageRange = 'under18';
      } else if (title.includes('posgrado') || title.includes('maestría') || title.includes('maestria') || title.includes('bicentenario') || title.includes('carolina') || title.includes('fulbright') || title.includes('reto')) {
        clone.typeCategory = 'postgraduate';
        clone.ageRange = 'over25';
      } else if (title.includes('técnica') || title.includes('tecnica') || title.includes('instituto') || org.includes('tecsup')) {
        clone.typeCategory = 'technical';
        clone.ageRange = '18to25';
      } else {
        clone.typeCategory = 'undergraduate';
        clone.ageRange = '18to25';
      }
    }
  } else if (cat === 'internship' || (cat === 'job' && (title.includes('practicante') || title.includes('trainee')))) {
    if (!clone.typeCategory) {
      if (title.includes('pre') || title.includes('estudiante')) {
        clone.typeCategory = 'pre-profesional';
      } else {
        clone.typeCategory = 'profesional';
      }
    }
  } else if (cat === 'volunteer') {
    if (!clone.typeCategory) {
      if (org.includes('techo') || title.includes('vivienda') || title.includes('comedor') || org.includes('alimentos') || title.includes('ancianos')) {
        clone.typeCategory = 'social';
      } else if (org.includes('cruz roja') || title.includes('sangre') || title.includes('salud')) {
        clone.typeCategory = 'salud';
      } else if (title.includes('amazonía') || title.includes('animal') || title.includes('ambiental') || org.includes('arbio') || org.includes('l.o.o.p')) {
        clone.typeCategory = 'ambiente';
      } else if (org.includes('enseña') || title.includes('matemáticas') || org.includes('crea+') || title.includes('educación') || title.includes('educativo')) {
        clone.typeCategory = 'educacion';
      } else {
        clone.typeCategory = 'civico';
      }
    }
  } else if (cat === 'competition') {
    if (!clone.typeCategory) {
      if (title.includes('hackathon') || title.includes('google') || title.includes('nasa') || title.includes('huawei') || title.includes('microsoft') || title.includes('solution') || title.includes('ict') || title.includes('imagine')) {
        clone.typeCategory = 'hackathon';
      } else if (title.includes('premio') || title.includes('juventud') || title.includes('student')) {
        clone.typeCategory = 'premios';
      } else if (title.includes('startup') || title.includes('hult') || title.includes('emprendimiento')) {
        clone.typeCategory = 'emprendimiento';
      } else {
        clone.typeCategory = 'ciencia';
      }
    }
  }

  // DEFAULT REQUIREMENTS, BENEFITS, STEPS IF EMPTY
  if (!clone.requirements || !clone.requirements.length) {
    clone.requirements = [
      'Cumplir con los requisitos y bases oficiales publicadas por la entidad convocante.',
      'Presentar documento de identidad oficial vigente (DNI o Carné de Extranjería).',
      'Disponibilidad para completar el proceso de postulación en las fechas programadas.'
    ];
  }
  if (!clone.benefits || !clone.benefits.length) {
    clone.benefits = [
      '100% de financiamiento o formación subvencionada sin costo para el participante.',
      'Acompañamiento especializado y constancia/certificación con validez oficial.',
      'Inserción a la red de talentos y egresados de Impulsa Joven Perú.'
    ];
  }
  if (!clone.steps || !clone.steps.length) {
    clone.steps = [
      'Revisar las bases oficiales y cronograma de postulación.',
      'Ingresar al enlace oficial de la institución convocante.',
      'Completar el registro con tus datos personales y adjuntar documentos.',
      'Esperar la publicación de resultados y confirmación de ingreso.'
    ];
  }

  return clone;
}

